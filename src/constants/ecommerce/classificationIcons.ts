export const CLASSIFICATION_ICONS: ClassificationIconOption[] =
  CLASSIFICATION_ICON_GROUPS.flatMap((g) => g.icons);

const ICON_BY_VALUE = new Map(CLASSIFICATION_ICONS.map((i) => [i.value, i]));

export const getClassificationIcon = (value?: string | null) =>
  value ? ICON_BY_VALUE.get(value) : undefined;
