/**
 * Icons selectable for product classifications (Group → Sub Category).
 * `value` is the plain string sent to the API as `icon` (kebab-case lucide
 * name, ≤ 100 chars). Grouped by Familie Munshi's storefront category types.
 */
export interface ClassificationIconOption {
  value: string;
  label: string;
  Icon: LucideIcon;
  /** Extra search terms (EN + DE). */
  keywords?: string;
}

export interface ClassificationIconGroup {
  group: string;
  icons: ClassificationIconOption[];
}

const opt = (
  value: string,
  label: string,
  Icon: LucideIcon,
  keywords?: string
): ClassificationIconOption => ({ value, label, Icon, keywords });

